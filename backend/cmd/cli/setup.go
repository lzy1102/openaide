func defaultL3Research(lang string) string {
	if lang == "zh" {
		return `## 研究模式
- 先收集信息，再形成结论。
- 声称"缺少 X"或"X 不安全"之前，先搜索 X 是否在代码库其他地方已经存在。
- 不要不检查调用链就报告"缺少"。
- 结尾给出可执行的行动计划：先做什么、预估工作量。`
	}
	return `## Research Mode
- Gather information before forming conclusions.
- Before claiming "X is missing" or "X is unsafe": search for X elsewhere in the codebase first.
- Never report "missing" without checking the call chain.
- End with a concrete action plan with estimated effort.`
}

func testConnection(baseURL, apiKey, model string) bool {
	client := &http.Client{Timeout: 10 * time.Second}
	body := strings.NewReader(fmt.Sprintf(`{"model":"%s","messages":[{"role":"user","content":"hi"}],"max_tokens":5}`, model))
	req, _ := http.NewRequest("POST", baseURL+"/chat/completions", body)
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer "+apiKey)
	resp, err := client.Do(req)
	if err != nil {
		return false
	}
	resp.Body.Close()
	return resp.StatusCode == 200
}
